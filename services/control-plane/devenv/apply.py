"""Apply engine: render settings into compose.override.yaml + stack.env, then `docker compose up`."""

import difflib
import json
import os
import shlex
import subprocess
import threading

import yaml

from .auth import issue_token
from .config import Config
from .db import Database
from .secretstore import SecretStore
from .settings_schema import Settings

SECRET_ENV = {
    "github_token": "GITHUB_TOKEN",
    "openai_api_key": "OPENAI_API_KEY",
    "anthropic_api_key": "ANTHROPIC_API_KEY",
    "claude_code_oauth_token": "CLAUDE_CODE_OAUTH_TOKEN",
    "cloudflare_tunnel_token": "TUNNEL_TOKEN",
}


def ensure_worker_token(db: Database, secrets: SecretStore) -> str:
    token = secrets.get("worker_token")
    if not token:
        token = issue_token(db, "worker", "workers")
        secrets.set("worker_token", token)
    return token


def render(settings: Settings, secrets: SecretStore, worker_token: str) -> tuple[str, dict[str, str]]:
    """Return (override yaml, env dict). Env values are used for compose interpolation only."""
    profiles = []
    if settings.agents.openhands_enabled:
        profiles.append("openhands")
    cf = settings.cloudflare
    if cf.tunnel_enabled and cf.mode == "quick":
        profiles.append("quicktunnel")
    elif cf.tunnel_enabled and secrets.get("cloudflare_tunnel_token"):
        profiles.append("tunnel")
    env = {
        "COMPOSE_PROFILES": ",".join(profiles),
        "CLAUDE_MODEL": settings.agents.claude.model,
        "CODEX_MODEL": settings.agents.codex.model,
        "GIT_USER_NAME": settings.github.git_user_name,
        "GIT_USER_EMAIL": settings.github.git_user_email,
        "WORKER_TOKEN": worker_token,
    }
    for name, var in SECRET_ENV.items():
        env[var] = secrets.get(name) or ""
    override = {
        "services": {
            "worker-claude": {"deploy": {"replicas": settings.agents.claude.count}},
            "worker-codex": {"deploy": {"replicas": settings.agents.codex.count}},
        }
    }
    header = "# Generated by the control plane apply engine. Do not edit; change settings in the UI.\n"
    return header + yaml.safe_dump(override, sort_keys=True), env


def env_text(env: dict[str, str]) -> str:
    return "".join(f"{k}={shlex.quote(v)}\n" for k, v in sorted(env.items()))


def masked(env: dict[str, str]) -> str:
    secret_vars = set(SECRET_ENV.values()) | {"WORKER_TOKEN"}
    return env_text({k: ("********" if k in secret_vars and v else v) for k, v in env.items()})


def preview(cfg: Config, override: str, env: dict[str, str]) -> str:
    old_override = cfg.override_path.read_text() if cfg.override_path.exists() else ""
    old_env = ""
    if cfg.env_path.exists():
        old = {}
        for line in cfg.env_path.read_text().splitlines():
            if "=" in line:
                k, v = line.split("=", 1)
                old[k] = shlex.split(v)[0] if v else ""
        old_env = masked(old)
    diff = list(
        difflib.unified_diff(
            old_override.splitlines(),
            override.splitlines(),
            "compose.override.yaml (current)",
            "compose.override.yaml (new)",
            lineterm="",
        )
    )
    diff += list(
        difflib.unified_diff(
            old_env.splitlines(), masked(env).splitlines(), "stack.env (current)", "stack.env (new)", lineterm=""
        )
    )
    return "\n".join(diff) or "No changes."


def compose_cmd(cfg: Config, *args: str) -> list[str]:
    cmd = [
        "docker",
        "compose",
        "--project-name",
        "devenv",
        "--project-directory",
        str(cfg.stack_dir),
        "-f",
        str(cfg.stack_dir / "compose.yaml"),
    ]
    if cfg.override_path.exists():
        cmd += ["-f", str(cfg.override_path)]
    if cfg.env_path.exists():
        cmd += ["--env-file", str(cfg.env_path)]
    return cmd + list(args)


# Services the apply engine manages, by compose profile ("" = always on). The control
# plane and caddy are left alone: recreating the control plane from inside itself kills
# the `docker compose up` doing it, which leaves the stack down.
MANAGED_SERVICES = {
    "worker-claude": "",
    "worker-codex": "",
    "openhands": "openhands",
    "cloudflared": "tunnel",
    "cloudflared-quick": "quicktunnel",
}


def managed_commands(cfg: Config, env: dict[str, str]) -> list[list[str]]:
    """Compose commands that bring the managed services to the desired state."""
    active = set(filter(None, env.get("COMPOSE_PROFILES", "").split(",")))
    up = [svc for svc, prof in MANAGED_SERVICES.items() if not prof or prof in active]
    down = [svc for svc, prof in MANAGED_SERVICES.items() if prof and prof not in active]
    cmds = [compose_cmd(cfg, "up", "-d", "--no-deps", *up)]
    if down:
        cmds.append(compose_cmd(cfg, "rm", "--stop", "--force", *down))
    return cmds


def tunnel_wanted(settings: Settings, secrets: SecretStore) -> bool:
    cf = settings.cloudflare
    return bool(
        cf.tunnel_enabled
        and cf.mode == "named"
        and cf.manage_with_terraform
        and secrets.get("cloudflare_api_token")
        and cf.account_id
        and cf.zone
        and cf.hostname
    )


class ApplyEngine:
    def __init__(self, cfg: Config, db: Database, secrets: SecretStore):
        self.cfg, self.db, self.secrets = cfg, db, secrets
        self._lock = threading.Lock()

    def start(self, settings: Settings) -> int:
        run_id = self.db.run("INSERT INTO apply_runs(status) VALUES ('running')").lastrowid
        thread = threading.Thread(target=self._run_all, args=(run_id, settings), daemon=True)
        thread.start()
        return run_id

    def _run_all(self, run_id: int, settings: Settings) -> None:
        if (
            tunnel_wanted(settings, self.secrets)
            and (self.cfg.stack_dir / "terraform" / "cloudflare" / "tf.sh").exists()
        ):
            if not self._terraform(run_id, settings):
                self._finish(run_id, "failed")
                return
        override, env = render(settings, self.secrets, ensure_worker_token(self.db, self.secrets))
        self._run(run_id, override, env)

    def _terraform(self, run_id: int, settings: Settings) -> bool:
        """Create/update the Cloudflare tunnel, DNS and Access with Terraform, then store the tunnel token."""
        tf_dir = self.cfg.stack_dir / "terraform" / "cloudflare"
        cf = settings.cloudflare
        env = {
            **os.environ,
            "CLOUDFLARE_API_TOKEN": self.secrets.get("cloudflare_api_token") or "",
            "TF_VAR_account_id": cf.account_id,
            "TF_VAR_zone": cf.zone,
            "TF_VAR_hostname": cf.hostname,
            "TF_VAR_allowed_emails": json.dumps(cf.access_emails),
            "TF_DATA_DIR": str(self.cfg.state_dir / "terraform"),
            "TF_IN_AUTOMATION": "1",
            "CHECKPOINT_DISABLE": "1",
        }
        self._log(run_id, f"== Terraform: Cloudflare tunnel for {cf.hostname}\n")
        for args in (["apply", "-no-color"], ["output", "-no-color", "-raw", "tunnel_token"]):
            proc = subprocess.run(
                [str(tf_dir / "tf.sh"), *args], cwd=tf_dir, env=env, capture_output=True, text=True, timeout=900
            )
            if args[0] == "output":
                if proc.returncode != 0 or not proc.stdout.strip():
                    self._log(run_id, f"Could not read tunnel token: {proc.stderr[-2000:]}\n")
                    return False
                self.secrets.set("cloudflare_tunnel_token", proc.stdout.strip())
                self._log(run_id, "Stored the tunnel token.\n")
                tokens = subprocess.run(
                    [str(tf_dir / "tf.sh"), "output", "-no-color", "-json", "service_tokens"],
                    cwd=tf_dir,
                    env=env,
                    capture_output=True,
                    text=True,
                    timeout=300,
                )
                if tokens.returncode == 0 and tokens.stdout.strip():
                    self.secrets.set("cloudflare_access_service_tokens", tokens.stdout.strip())
                    self._log(run_id, "Stored the Access service tokens for controllers.\n")
                continue
            self._log(run_id, proc.stdout[-8000:] + proc.stderr[-4000:])
            if proc.returncode != 0:
                self._log(run_id, "Terraform failed.\n")
                return False
        return True

    def _log(self, run_id: int, text: str) -> None:
        self.db.run("UPDATE apply_runs SET log = log || ? WHERE id = ?", text, run_id)

    def _finish(self, run_id: int, status: str) -> None:
        self.db.run(
            "UPDATE apply_runs SET status = ?, finished_at = strftime('%Y-%m-%dT%H:%M:%fZ','now') WHERE id = ?",
            status,
            run_id,
        )

    def _run(self, run_id: int, override: str, env: dict[str, str]) -> None:
        with self._lock:
            try:
                (self.cfg.state_dir / "agent-config").mkdir(mode=0o755, exist_ok=True)
                self.cfg.override_path.write_text(override)
                fd = os.open(self.cfg.env_path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
                with os.fdopen(fd, "w") as f:
                    f.write(env_text(env))
                self._log(run_id, f"Wrote {self.cfg.override_path} and {self.cfg.env_path}\n")
                if not self.cfg.docker_enabled:
                    self._log(run_id, "Docker disabled (DEVENV_DOCKER=0); skipping compose up\n")
                    self._finish(run_id, "succeeded")
                    return
                code = 0
                for cmd in managed_commands(self.cfg, env):
                    self._log(run_id, "$ " + " ".join(cmd) + "\n")
                    proc = subprocess.Popen(cmd, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
                    assert proc.stdout
                    for line in proc.stdout:
                        self._log(run_id, line)
                    code = proc.wait()
                    if code != 0:
                        break
                self._finish(run_id, "succeeded" if code == 0 else "failed")
            except Exception as e:  # noqa: BLE001 - surface any failure in the run log
                self._log(run_id, f"ERROR: {e}\n")
                self._finish(run_id, "failed")


def running_workers(cfg: Config) -> dict[str, int]:
    """Count running worker containers per provider via `docker compose ps`."""
    import json

    out = subprocess.run(compose_cmd(cfg, "ps", "--format", "json"), capture_output=True, text=True, timeout=60)
    counts = {"claude": 0, "codex": 0}
    for line in out.stdout.splitlines():
        line = line.strip()
        if not line:
            continue
        items = json.loads(line)
        for c in items if isinstance(items, list) else [items]:
            svc = c.get("Service", "")
            if c.get("State") == "running" and svc.startswith("worker-"):
                counts[svc.removeprefix("worker-")] = counts.get(svc.removeprefix("worker-"), 0) + 1
    return counts


def reconcile_workers(engine: "ApplyEngine", desired: dict[str, int]) -> str | None:
    """Supervisor: if the number of running workers differs from settings, scale them back. Returns a note or None."""
    cfg = engine.cfg
    if not cfg.docker_enabled or not cfg.override_path.exists() or engine._lock.locked():
        return None
    actual = running_workers(cfg)
    if all(actual.get(p, 0) == n for p, n in desired.items()):
        return None
    with engine._lock:
        subprocess.run(
            compose_cmd(cfg, "up", "-d", "--no-recreate", "--no-deps", "worker-claude", "worker-codex"),
            capture_output=True,
            timeout=600,
        )
    return f"scaled workers from {actual} to {desired}"
