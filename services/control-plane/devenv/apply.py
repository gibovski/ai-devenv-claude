"""Apply engine: render settings into compose.override.yaml + stack.env, then `docker compose up`."""

import difflib
import os
import shlex
import subprocess
import threading

import yaml

from .auth import issue_token
from .config import Config
from .db import Database
from .secretstore import SecretStore
from .settings_schema import Settings

SECRET_ENV = {
    "github_token": "GITHUB_TOKEN",
    "openai_api_key": "OPENAI_API_KEY",
    "anthropic_api_key": "ANTHROPIC_API_KEY",
    "cloudflare_tunnel_token": "TUNNEL_TOKEN",
}


def ensure_worker_token(db: Database, secrets: SecretStore) -> str:
    token = secrets.get("worker_token")
    if not token:
        token = issue_token(db, "worker", "workers")
        secrets.set("worker_token", token)
    return token


def render(settings: Settings, secrets: SecretStore, worker_token: str) -> tuple[str, dict[str, str]]:
    """Return (override yaml, env dict). Env values are used for compose interpolation only."""
    profiles = []
    if settings.agents.openhands_enabled:
        profiles.append("openhands")
    if settings.cloudflare.tunnel_enabled and secrets.get("cloudflare_tunnel_token"):
        profiles.append("tunnel")
    env = {
        "COMPOSE_PROFILES": ",".join(profiles),
        "CLAUDE_MODEL": settings.agents.claude.model,
        "CODEX_MODEL": settings.agents.codex.model,
        "GIT_USER_NAME": settings.github.git_user_name,
        "GIT_USER_EMAIL": settings.github.git_user_email,
        "WORKER_TOKEN": worker_token,
    }
    for name, var in SECRET_ENV.items():
        env[var] = secrets.get(name) or ""
    override = {
        "services": {
            "worker-claude": {"deploy": {"replicas": settings.agents.claude.count}},
            "worker-codex": {"deploy": {"replicas": settings.agents.codex.count}},
        }
    }
    header = "# Generated by the control plane apply engine. Do not edit; change settings in the UI.\n"
    return header + yaml.safe_dump(override, sort_keys=True), env


def env_text(env: dict[str, str]) -> str:
    return "".join(f"{k}={shlex.quote(v)}\n" for k, v in sorted(env.items()))


def masked(env: dict[str, str]) -> str:
    secret_vars = set(SECRET_ENV.values()) | {"WORKER_TOKEN"}
    return env_text({k: ("********" if k in secret_vars and v else v) for k, v in env.items()})


def preview(cfg: Config, override: str, env: dict[str, str]) -> str:
    old_override = cfg.override_path.read_text() if cfg.override_path.exists() else ""
    old_env = ""
    if cfg.env_path.exists():
        old = {}
        for line in cfg.env_path.read_text().splitlines():
            if "=" in line:
                k, v = line.split("=", 1)
                old[k] = shlex.split(v)[0] if v else ""
        old_env = masked(old)
    diff = list(
        difflib.unified_diff(
            old_override.splitlines(),
            override.splitlines(),
            "compose.override.yaml (current)",
            "compose.override.yaml (new)",
            lineterm="",
        )
    )
    diff += list(
        difflib.unified_diff(
            old_env.splitlines(), masked(env).splitlines(), "stack.env (current)", "stack.env (new)", lineterm=""
        )
    )
    return "\n".join(diff) or "No changes."


def compose_cmd(cfg: Config, *args: str) -> list[str]:
    cmd = [
        "docker",
        "compose",
        "--project-name",
        "devenv",
        "--project-directory",
        str(cfg.stack_dir),
        "-f",
        str(cfg.stack_dir / "compose.yaml"),
    ]
    if cfg.override_path.exists():
        cmd += ["-f", str(cfg.override_path)]
    if cfg.env_path.exists():
        cmd += ["--env-file", str(cfg.env_path)]
    return cmd + list(args)


class ApplyEngine:
    def __init__(self, cfg: Config, db: Database, secrets: SecretStore):
        self.cfg, self.db, self.secrets = cfg, db, secrets
        self._lock = threading.Lock()

    def start(self, settings: Settings) -> int:
        override, env = render(settings, self.secrets, ensure_worker_token(self.db, self.secrets))
        run_id = self.db.run("INSERT INTO apply_runs(status) VALUES ('running')").lastrowid
        thread = threading.Thread(target=self._run, args=(run_id, override, env), daemon=True)
        thread.start()
        return run_id

    def _log(self, run_id: int, text: str) -> None:
        self.db.run("UPDATE apply_runs SET log = log || ? WHERE id = ?", text, run_id)

    def _finish(self, run_id: int, status: str) -> None:
        self.db.run(
            "UPDATE apply_runs SET status = ?, finished_at = strftime('%Y-%m-%dT%H:%M:%fZ','now') WHERE id = ?",
            status,
            run_id,
        )

    def _run(self, run_id: int, override: str, env: dict[str, str]) -> None:
        with self._lock:
            try:
                self.cfg.override_path.write_text(override)
                fd = os.open(self.cfg.env_path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
                with os.fdopen(fd, "w") as f:
                    f.write(env_text(env))
                self._log(run_id, f"Wrote {self.cfg.override_path} and {self.cfg.env_path}\n")
                if not self.cfg.docker_enabled:
                    self._log(run_id, "Docker disabled (DEVENV_DOCKER=0); skipping compose up\n")
                    self._finish(run_id, "succeeded")
                    return
                cmd = compose_cmd(self.cfg, "up", "-d", "--remove-orphans")
                self._log(run_id, "$ " + " ".join(cmd) + "\n")
                proc = subprocess.Popen(cmd, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
                assert proc.stdout
                for line in proc.stdout:
                    self._log(run_id, line)
                code = proc.wait()
                self._finish(run_id, "succeeded" if code == 0 else "failed")
            except Exception as e:  # noqa: BLE001 - surface any failure in the run log
                self._log(run_id, f"ERROR: {e}\n")
                self._finish(run_id, "failed")
