"""A stable https://<name>.<account>.workers.dev address in front of the quick tunnel.

The quick tunnel's trycloudflare.com address changes whenever cloudflared restarts. With the user's
own Cloudflare API token (entered in Settings, never in the image), this module deploys a tiny Worker
on their free workers.dev subdomain that proxies to the current quick-tunnel address, and redeploys it
whenever that address changes. The app's own login still guards everything behind it.
"""

import json
import logging
import secrets as pysecrets
import time

import httpx

from .db import Database
from .secretstore import SecretStore
from .state import kv_get, kv_set, load_settings
from .tunnel import quick_tunnel_url

log = logging.getLogger("devenv.stable")
API = "https://api.cloudflare.com/client/v4"
STATE_KEY = "stable_address"

WORKER_JS = """// Generated by the AI dev environment. Proxies this stable address to the VM's current quick tunnel.
const TARGET = %s;
export default {
  async fetch(request) {
    const url = new URL(request.url);
    const dest = new URL(url.pathname + url.search, TARGET);
    const headers = new Headers(request.headers);
    headers.set("X-Forwarded-Host", url.host);
    headers.set("X-Forwarded-Proto", "https");
    const resp = await fetch(new Request(dest, { method: request.method, headers, body: request.body, redirect: "manual" }));
    const loc = resp.headers.get("Location");
    if (!loc || !loc.startsWith(TARGET)) return resp;
    const out = new Response(resp.body, resp);
    out.headers.set("Location", url.origin + loc.slice(TARGET.length));
    return out;
  },
};
"""


def worker_script(target: str) -> str:
    return WORKER_JS % json.dumps(target.rstrip("/"))


def worker_name(db: Database) -> str:
    """The name from Settings, or a per-install default made on first use (never baked into the image)."""
    name = load_settings(db).cloudflare.stable_name.strip().lower()
    if name:
        return name
    name = kv_get(db, "stable_default_name", "")
    if not name:
        name = f"devenv-{pysecrets.token_hex(3)}"
        kv_set(db, "stable_default_name", name)
    return name


def status(db: Database) -> dict:
    s = load_settings(db).cloudflare
    st = kv_get(db, STATE_KEY, {}) or {}
    enabled = s.tunnel_enabled and s.mode == "quick" and s.stable_enabled
    return {
        "enabled": enabled,
        "name": worker_name(db),
        "url": st.get("url", "") if enabled else "",
        "error": st.get("error", "") if enabled else "",
    }


class CloudflareError(RuntimeError):
    pass


def _call(client: httpx.Client, method: str, path: str, **kw) -> dict:
    r = client.request(method, API + path, **kw)
    try:
        data = r.json()
    except ValueError:
        data = {}
    if r.status_code >= 400 or not data.get("success", False):
        errs = "; ".join(e.get("message", "") for e in data.get("errors", [])) or f"HTTP {r.status_code}"
        raise CloudflareError(errs)
    return data.get("result") or {}


def publish(token: str, account_id: str, name: str, target: str, client: httpx.Client | None = None) -> str:
    """Deploy the proxy Worker and enable its workers.dev route. Returns the stable URL."""
    own = client is None
    client = client or httpx.Client(headers={"Authorization": f"Bearer {token}"}, timeout=30)
    try:
        acct = f"/accounts/{account_id}"
        try:
            sub = _call(client, "GET", f"{acct}/workers/subdomain").get("subdomain", "")
        except CloudflareError:
            sub = ""
        if not sub:
            raise CloudflareError(
                "Your account has no workers.dev subdomain yet. Open Workers & Pages in the Cloudflare dashboard once to pick one."
            )
        meta = {"main_module": "worker.js", "compatibility_date": "2025-01-01"}
        files = {
            "metadata": (None, json.dumps(meta), "application/json"),
            "worker.js": ("worker.js", worker_script(target), "application/javascript+module"),
        }
        _call(client, "PUT", f"{acct}/workers/scripts/{name}", files=files)
        _call(
            client,
            "POST",
            f"{acct}/workers/scripts/{name}/subdomain",
            json={"enabled": True, "previews_enabled": False},
        )
        return f"https://{name}.{sub}.workers.dev"
    finally:
        if own:
            client.close()


def sync(db: Database, store: SecretStore, client: httpx.Client | None = None, target: str | None = None) -> None:
    """Background job: redeploy the Worker when the quick-tunnel address (or the name) changes."""
    cf = load_settings(db).cloudflare
    if not (cf.tunnel_enabled and cf.mode == "quick" and cf.stable_enabled):
        return
    st = kv_get(db, STATE_KEY, {}) or {}
    token, account = store.get("cloudflare_api_token"), cf.account_id.strip()
    if not token or not account:
        kv_set(db, STATE_KEY, {**st, "error": "Needs a Cloudflare API token and account ID (Settings, Remote access)."})
        return
    target = quick_tunnel_url() if target is None else target
    if not target:
        return
    name = worker_name(db)
    # Retry a failed deploy at most every 5 minutes; otherwise only redeploy on change.
    if st.get("target") == target and st.get("name") == name and st.get("account") == account:
        if not st.get("error") or time.time() - st.get("at", 0) < 300:
            return
    try:
        url = publish(token, account, name, target, client)
        kv_set(
            db,
            STATE_KEY,
            {"name": name, "account": account, "target": target, "url": url, "error": "", "at": time.time()},
        )
        log.info("stable address %s now points at %s", url, target)
    except (CloudflareError, httpx.HTTPError) as e:
        kv_set(
            db,
            STATE_KEY,
            {**st, "name": name, "account": account, "target": target, "error": str(e), "at": time.time()},
        )
        log.warning("stable address update failed: %s", e)
